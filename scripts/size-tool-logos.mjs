#!/usr/bin/env node
/**
 * Size the tooling strip's logos so they carry the same visual weight.
 *
 * A fixed box makes logos look uneven: some SVGs sit in empty canvas, and a solid
 * square (TypeScript) has far more ink than an outline (Airflow). For each logo in
 * public/tools, this renders the SVG, finds the box around its ink and how densely
 * it fills that box, then picks a display size:
 *   - the ink box's area shrinks as density rises (by density^0.4, so dense
 *     logos are smaller but are not shrunk to the same ink as outlines)
 *   - the result stays inside the 38px tile
 *   - a tool's optional `scale` in content/tools.json corrects marks this misjudges
 *     (Remotion's faint halos, shadcn/ui's thin strokes, Next.js's solid disc)
 * It writes content/tool-sizes.json: the <img> size and the offset that centres the ink.
 *
 * Usage: node scripts/size-tool-logos.mjs   (run after scripts/fetch-tool-logos.py)
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = join(ROOT, "public", "tools");
const OUT = join(ROOT, "content", "tool-sizes.json");
const { tools } = JSON.parse(
  readFileSync(join(ROOT, "content", "tools.json"), "utf8"),
);

const RENDER = 480; // px on the long side when measuring
const SIDE = 24; // px: the ink box side of a square logo at reference density
const DENSITY = 0.5; // reference density: ink area / ink box area
const MAX_W = 32; // px: keeps the logo, scaled 1.1x on hover, inside the 38px tile
const MAX_H = 26;

const round = (n) => Math.round(n * 10) / 10;

async function measure(file) {
  const svg = readFileSync(file);
  const { width, height } = await sharp(svg).metadata();
  const k = RENDER / Math.max(width, height);
  const { data, info } = await sharp(svg, { density: 72 * k })
    .resize(Math.round(width * k), Math.round(height * k), { fit: "fill" })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  let ink = 0,
    x0 = Infinity,
    y0 = Infinity,
    x1 = -1,
    y1 = -1;
  for (let y = 0; y < info.height; y++)
    for (let x = 0; x < info.width; x++) {
      const a = data[(y * info.width + x) * 4 + 3] / 255;
      ink += a;
      if (a < 0.5) continue; // translucent layers, glows and shadows don't set the box
      x0 = Math.min(x0, x);
      x1 = Math.max(x1, x);
      y0 = Math.min(y0, y);
      y1 = Math.max(y1, y);
    }
  const bw = x1 - x0 + 1,
    bh = y1 - y0 + 1;
  return {
    iw: info.width,
    ih: info.height,
    x0,
    y0,
    bw,
    bh,
    density: ink / (bw * bh),
  };
}

function size({ iw, ih, x0, y0, bw, bh, density }, scale = 1) {
  const area = SIDE * SIDE * (DENSITY / density) ** 0.4;
  const ratio = bw / bh;
  let w = Math.sqrt(area * ratio),
    h = Math.sqrt(area / ratio);
  const fit = Math.min(1, MAX_W / w, MAX_H / h);
  w *= fit;
  h *= fit;
  // the whole SVG at the scale that gives its ink box w x h, moved so the ink is centred
  const s = (w / bw) * scale;
  return {
    w: round(iw * s),
    h: round(ih * s),
    x: round((iw / 2 - (x0 + bw / 2)) * s),
    y: round((ih / 2 - (y0 + bh / 2)) * s),
  };
}

const sizes = {};
for (const f of readdirSync(DIR)
  .filter((f) => f.endsWith(".svg"))
  .sort()) {
  const id = f.replace(/\.svg$/, "");
  sizes[id] = size(await measure(join(DIR, f)), tools[id]?.scale);
}
writeFileSync(
  OUT,
  JSON.stringify(
    {
      _comment:
        "Generated by scripts/size-tool-logos.mjs: each logo's <img> size and ink-centring offset, in px.",
      ...sizes,
    },
    null,
    2,
  ) + "\n",
);
console.log(
  `${Object.keys(sizes).length} logos -> ${OUT.slice(ROOT.length + 1)}`,
);
